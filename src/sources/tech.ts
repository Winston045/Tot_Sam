/**
 * Есть ли в русской подписи военная техника. Канал @War_ThunDep - только
 * техника, а у memorial и PastVu подписи готовые: по ним кадр без техники
 * отсекается ещё до Gemini и не тратит квоту.
 */
export const TECH_RU = new RegExp(
  [
    "танк", "танкетк", "самоходн", "штурмов\\S* орудие", "броне", "БТР", "БМП",
    "самол[её]т", "истребител", "бомбардировщ", "штурмовик", "вертол[её]т", "гидросамол", "дирижабл",
    "корабл", "крейсер", "эсмин", "линкор", "подлодк", "подводн\\S* лодк", "катер", "тральщик", "авианос",
    "орудие", "орудия", "орудий", "пушк", "гаубиц", "миномёт", "миномет", "зенитн", "зенитк", "катюш",
    "реактивн", "ракет", "тягач", "бронепоезд",
    "(?:^|[^\\p{L}])САУ(?:$|[^\\p{L}])",
    // обозначения: Т-34, КВ-1, ИС-2, Ил-2, Як-3, Bf 109, Ju 87, Pz.IV, StuG III, Sd.Kfz. 251
    "(?:^|[^\\p{L}])(?:Т|T|КВ|ИС|ИСУ|СУ|Ил|Як|Ла|Ми|Су|Ту|Пе|МиГ|Bf|Ju|Me|He|Pz|StuG|Sd\\.?\\s?Kfz)[-\\s.]{0,2}[IVX\\d]",
  ].join("|"),
  "iu",
);

export function hasTechRu(text: string | undefined): boolean {
  return TECH_RU.test(text ?? "");
}
