/**
 * Похоже ли на голые место и год («Италия, 1943 год.») - штатную цитату
 * обычного поста. Используется и сборкой подписи, и редактором цитат.
 */
export function isBarePlaceDate(text: string): boolean {
  const t = text.trim();
  if (t.length === 0 || t.length > 60) return false;
  if (!/(18|19|20)\d{2}/.test(t)) return false;
  const sentences = t.split(/\.\s+/).filter(Boolean);
  return sentences.length <= 2;
}

/**
 * Сколько описательных предложений в теле подписи.
 *
 * Строки и обрывки вида «Ливия, декабрь 1942 года.» не считаются: это
 * не описание, а место и дата (в старом резерве они встречаются строкой
 * тела; с 07.09 сборка переносит такую строку в отдельную цитату места).
 * Мера нужна не для отбраковки - выкидывать готовый кадр из-за
 * лишнего предложения дороже, чем оставить его, - а чтобы в логе прогона
 * было видно, слушается ли модель правила «описание в одно предложение».
 */
export function descriptiveSentences(caption: string): number {
  const lines = caption
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.length > 0 && !isBarePlaceDate(l));
  return lines
    .join(" ")
    .split(/(?<=[.!?])\s+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0 && !isBarePlaceDate(s)).length;
}

/** Требует ли лицензия строку атрибуции. PD - нет, CC-BY-* - да. */
export function needsAttribution(license: string): boolean {
  return /cc[- ]by/i.test(license);
}

/** Футер поста: хэштеги канала. Его же ищет splitFooter. */
export const POST_FOOTER = "#photo #история";

function escapeHtml(t: string): string {
  return t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** **название** - жирным; одиночные и непарные звёздочки убираем. */
export function boldMarks(text: string): string {
  return escapeHtml(text)
    .replace(/\*\*([^*\n]+?)\*\*/g, "<b>$1</b>")
    .replace(/\*/g, "");
}

/** Дата курсивом с точкой: «1944 год» → «<i>1944 год.</i>». */
function dateHtml(date: string | undefined): string {
  let d = (date ?? "").trim().replace(/[.\s]+$/, "");
  // дата начинает своё предложение: «Лето 1941 года.», а не «лето...»
  d = d.charAt(0).toUpperCase() + d.slice(1);
  return d ? ` <i>${escapeHtml(d)}.</i>` : "";
}

/**
 * Собирает финальный caption_html в формате канала:
 * «<b>Техника</b> описание. <i>1944 год.</i>», ниже необязательная цитата,
 * через пустую строку - хэштеги. Подписи канала и ссылок нет.
 */
export function assembleCaptionHtml(
  generated: GeneratedCaption,
  _item: Pick<RawItem, "license" | "attribution">,
  _channel: AppConfig["channel"],
): string {
  let body = boldMarks(generated.caption.trim().replace(/\s*\n\s*/g, " "));
  if (body && !/[.!?…»"]$/.test(body)) body += ".";
  body += dateHtml(generated.date);
  const quote = (generated.quote ?? "").trim();
  if (quote) {
    // длинная цитата свёрнута и раскрывается по клику
    const tag = quote.length > 200 ? "<blockquote expandable>" : "<blockquote>";
    body += `\n${tag}${escapeHtml(quote)}</blockquote>`;
  }
  return `${body}\n\n${POST_FOOTER}`;
}
